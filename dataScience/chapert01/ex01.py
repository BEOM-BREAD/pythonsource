# -*- coding: utf-8 -*-
import pandas as pd

"""
[학습 목표]
- pandas DataFrame이 '엑셀 표'와 비슷하다는 감을 잡는다.
- 딕셔너리 -> DataFrame 변환 방법을 익힌다.
- head(), info(), describe()로 데이터를 빠르게 훑어보는 습관을 들인다.

[강의 포인트]
- "엑셀에서 열 제목이 딕셔너리의 key, 각 행이 리스트의 원소"라고 비유하면 이해가 빠름.
- describe()는 숫자 컬럼에만 적용된다는 점을 강조 (문자열 컬럼은 빠짐).
"""

# 1. 딕셔너리로 데이터 준비 (key = 컬럼명, value = 각 학생의 값 리스트)
game_data = {
    "이름": ["김민준", "이서연", "박도윤", "최지우", "정하윤"],
    "게임종류": ["롤", "발로란트", "롤", "오버워치", "발로란트"],
    "최고점수": [2450, 1980, 3120, 2760, 2210],
    "플레이시간_시간": [120, 85, 200, 150, 95],
}

# 2. DataFrame 생성
df = pd.DataFrame(game_data)
print("=== 전체 데이터 ===")
print(df)

# 3. head() : 상위 n개 행만 미리보기 (기본값 5)
print("\n=== head(3) : 상위 3개만 보기 ===")
print(df.head(3))

# 4. info() : 컬럼별 데이터 타입, 결측치 개수, 메모리 사용량 확인
print("\n=== info() : 데이터 구조 확인 ===")
df.info()

# 5. describe() : 숫자 컬럼의 통계 요약 (평균, 표준편차, 최솟값, 최댓값 등)
print("\n=== describe() : 숫자 데이터 통계 요약 ===")
print(df.describe())

# 6. 컬럼 하나만 뽑아보기 (Series 형태로 반환됨)
print("\n=== '최고점수' 컬럼만 보기 (Series) ===")
print(df["최고점수"])
print("타입:", type(df["최고점수"]))